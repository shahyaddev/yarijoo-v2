import { NextResponse } from 'next/server'
import { Pool } from 'pg'

const pool = new Pool({ connectionString: 'postgresql://yarijoo:yarijoo_dev_pass@localhost:5432/yarijoo_v2' })

export async function GET() {
    try {
        const { rows } = await pool.query(`
      SELECT cp.*,
        COUNT(cpi.id)::int as item_count
      FROM composite_packages cp
      LEFT JOIN composite_package_items cpi ON cpi.package_id = cp.id
      GROUP BY cp.id
      ORDER BY cp.created_at DESC
    `)
        return NextResponse.json({ success: true, data: rows })
    } catch (e: unknown) {
        return NextResponse.json({ success: false, error: (e as Error).message }, { status: 500 })
    }
}

export async function POST(req: Request) {
    try {
        const body = await req.json()
        const { title, description, price, sale_price, items } = body

        const client = await pool.connect()
        try {
            await client.query('BEGIN')

            const pkgRes = await client.query(
                `INSERT INTO composite_packages (title, description, price, sale_price)
         VALUES ($1, $2, $3, $4) RETURNING id`,
                [title, description || null, price || 0, sale_price || null]
            )
            const pkgId = pkgRes.rows[0].id

            if (items?.length) {
                for (let i = 0; i < items.length; i++) {
                    const item = items[i]
                    await client.query(
                        `INSERT INTO composite_package_items (package_id, item_type, item_id, item_title, sort_order)
             VALUES ($1, $2, $3, $4, $5)`,
                        [pkgId, item.item_type, item.item_id, item.item_title || '', i + 1]
                    )
                }
            }

            await client.query('COMMIT')
            return NextResponse.json({ success: true, data: { id: pkgId } })
        } catch (e) {
            await client.query('ROLLBACK')
            throw e
        } finally {
            client.release()
        }
    } catch (e: unknown) {
        return NextResponse.json({ success: false, error: (e as Error).message }, { status: 500 })
    }
}

export async function DELETE(req: Request) {
    try {
        const { searchParams } = new URL(req.url)
        const id = searchParams.get('id')
        if (!id) return NextResponse.json({ success: false, error: 'id required' }, { status: 400 })
        await pool.query('DELETE FROM composite_packages WHERE id = $1', [id])
        return NextResponse.json({ success: true })
    } catch (e: unknown) {
        return NextResponse.json({ success: false, error: (e as Error).message }, { status: 500 })
    }
}

export async function PATCH(req: Request) {
    try {
        const { searchParams } = new URL(req.url)
        const id = searchParams.get('id')
        if (!id) return NextResponse.json({ success: false, error: 'id required' }, { status: 400 })
        const body = await req.json()
        await pool.query(
            `UPDATE composite_packages SET is_active = $1, updated_at = NOW() WHERE id = $2`,
            [body.is_active, id]
        )
        return NextResponse.json({ success: true })
    } catch (e: unknown) {
        return NextResponse.json({ success: false, error: (e as Error).message }, { status: 500 })
    }
}
